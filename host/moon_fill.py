def design_short():
    """Reproduce SHORT with an alias-norm constrained, symmetric FIR fit.

    EN 302 307-1 Annex A/Table A.1, ideal 80 MS/s hold; fn = f/(Rs/2).
    Minimize L1 distance to a windowed RRC, subject to 0.10 dB mask reserve
    and another 3 dB beyond fn=1.7. Supporting planes impose the convex
    five-alias power upper bound. The lower bound uses the main alias alone.
    This designs linear coefficients; mask(quantized=True) is the final gate.
    """
    from scipy.optimize import linprog
    up, den, span, alpha = 12,5,7,.2
    n, k = up/den, span*up//2
    x = np.arange(k)-(span*up-1)/2
    upper, lower = (np.array(s.MASK[alpha][a]) for a in ('upper','lower'))
    fn = np.unique(np.r_[np.linspace(0,n,2401),upper[:,0],lower[:,0]])
    f = np.stack([2*np.cos(np.pi*(fn+2*j*n)[:,None]*x/up) for j in range(-2,3)],axis=1)
    hold, near = np.sinc(fn/(2*n)), fn <= lower[-1,0]
    hi = 10**((np.interp(fn,*upper.T)-.10)/20)/hold
    hi[fn >= 1.7] *= 10**(-3/20)
    lo = 10**((np.interp(fn[near],*lower.T)+.10)/20)/hold[near]
    target = s.corrected_rrc(alpha,up,span)[:k]/up
    a, b = np.r_[f[:,2],-f[:,2],-f[near,2]],np.r_[hi,hi,-lo]
    for _ in range(60):
        result = linprog(np.r_[np.zeros(k),np.ones(k)],
                         A_ub=np.r_[np.c_[a,np.zeros_like(a)],
                                    np.c_[np.eye(k),-np.eye(k)],np.c_[-np.eye(k),-np.eye(k)]],
                         b_ub=np.r_[b,target,-target],A_eq=np.c_[f[0],np.zeros_like(f[0])],
                         b_eq=[0,0,1,0,0],bounds=[(-.12,.12)]*k+[(0,None)]*k,method='highs')
        assert result.success,result.message
        h = result.x[:k]
        v = f@h
        norm = np.linalg.norm(v,axis=1)
        bad = norm > hi*(1+5e-5)
        if not bad.any(): return np.round(h*2**40).astype(np.int64)
        a = np.r_[a,np.einsum('fa,fak->fk',v[bad]/norm[bad,None],f[bad])]
        b = np.r_[b,hi[bad]]
    raise RuntimeError('alias constraints did not converge')


@lru_cache(None)
def prototype(name):
    up, den, span, alpha, bits, _ = MODES[name]
    # t in symbol periods; f in cycles/symbol. Hold Fs is up/den, not up.
    if span == 7 and alpha == .20 and (up,den) == (12,5):
        g = np.r_[SHORT,SHORT[::-1]]/2**40
    else:
        f = np.linspace(0, (1+alpha)/2, 16385)
        t = (np.arange(span*up) - (span*up-1)/2)/up
        a = s.rrc_response(f, alpha)/np.sinc(f/(up/den))
        g = 2*np.trapezoid(a*np.cos(2*np.pi*np.outer(t,f)), f, axis=1)
        g *= np.kaiser(len(g), 1)
    amax = 1 if bits == 3 else np.sqrt(.5)
    worst = np.abs(g.reshape(span,up)).sum(0).max()*amax
    return np.round(g*508/worst*256).astype(np.int64)


def taps(name, peak=128):
    # Each separately rounded part adds at most 0.5 LSB/axis.
    reserve = (len(MODES[name][-1])+1)//2
    return np.trunc(prototype(name)*(peak-reserve)/508).astype(np.int64)


