def loopback(name, modcod, output, receiver, native):
    import decode
    import dvbs2
    import onair
    up, den, _, alpha, bits, _ = MODES[name]
    assert (modcod < 12) == (bits == 2)
    block = block_samples(name)*den//up
    frames = 16
    data = np.frombuffer(onair.payload(modcod,frames,'N0CALL'),np.uint8).reshape(frames,-1)
    phase = []
    rate,modulation = onair.mode(modcod)
    for payload in data:
        bb = dvbs2.bbframe(np.unpackbits(payload),rate,ro=alpha)
        fec = dvbs2.fecframe(bb,rate)
        phase.append(dvbs2.plframe_phases(fec,rate,modulation=modulation))
    phase = np.concatenate(phase)
    pad = (-len(phase))%block
    phase = np.r_[np.full(2*block,1 if bits == 2 else 0),phase,np.full(pad,1 if bits == 2 else 0)].astype(np.uint8)
    words = shape(name,phase)
    output.mkdir(parents=True,exist_ok=True)
    packed = output/f'{name}-{modcod}.u16'
    native_words = output/f'{name}-{modcod}.words'
    pack(name,phase).astype('<u2').tofile(packed)
    subprocess.run([str(native),str(tuple(MODES).index(name)),str(packed),str(native_words)],check=True)
    actual = np.fromfile(native_words,dtype='<u4')
    assert np.array_equal(actual,words),name
    words = actual
    z = s.iq(words)
    iq = np.column_stack((z.real,z.imag)).astype('<i2')
    crc = zlib.crc32(iq.tobytes())
    golden = json.loads((ROOT/'tests/data/moon_waveform_crcs.json').read_text())
    assert crc == golden[f'{name}/{modcod}'],(name,modcod,crc)
    path = output/f'{name}-{modcod}.iq'
    iq.tofile(path)
    cf = output/f'{name}-{modcod}.cfile'
    # Drain the finite receiver's input block/lookahead. This zero tail is
    # not part of the C dump or its pinned IQ CRC and contains no data frames.
    np.r_[z/512,np.zeros(4096,complex)].astype('<c8').tofile(cf)
    record, got = decode.decode(cf,sample_rate=80e6,symbol_rate=80e6*den/up,alpha=alpha,
                                 receiver=receiver,log=output/f'{name}-{modcod}.log')
    per = data.shape[1]
    at = onair.stream_match(data.tobytes(),got,per)
    assert at is not None and len(got)//per >= (14 if bits == 2 else 12),record
    assert record['bch_failed_frames'] == 0 and record['ldpc_bit_flips'] == 0,record
    assert record['ldpc_checks_before'] == record['ldpc_checks_after'] == 0,record
    assert record['bch_corrected_bits'] == 0 and record['bbheader_rejected_frames'] == 0,record
    record.update(mode=name,modcod=modcod,source='native C shaper, Python encoder',input_frames=frames,
                  contiguous_frames=len(got)//per,payload_bit_errors=0,first_frame=at//per,
                  iq_crc32=crc,receiver_flush_samples=4096)
    (output/f'{name}-{modcod}.json').write_text(json.dumps(record,sort_keys=True)+'\n')
    return record


