"""Offline fill experiment. Rational RRC, independent tables and receiver checks. No devices."""
import argparse
from functools import lru_cache
import json
import pathlib
import subprocess
import tempfile
import zlib

import numpy as np
import shaper as s

ROOT = pathlib.Path(__file__).resolve().parents[1]
# up/den samples/symbol; output blocks always contain twelve samples.
MODES = {
    '8psk3': (3, 1, 6, .35, 3, ((-5,-4,-3), (-2,-1,0), (1,2,3))),
    'qpsk24': (12, 5, 9, .20, 2, ((-8,-7,-6,-5), (-4,-3,-2,-1), (0,1,2,3), (4,))),
    '8psk24': (12, 5, 9, .20, 3, ((-8,-7,-6), (-5,-4,-3), (-2,-1,0), (1,2,3), (4,))),
    '8psk3a20': (3, 1, 9, .20, 3, ((-8,-7,-6), (-5,-4,-3), (-2,-1,0), (1,2,3))),
}
HEADER = ROOT/'firmware/main/shaper_moon_taps.h'


@lru_cache(None)
def prototype(name):
    up, den, span, alpha, bits, _ = MODES[name]
    # t in symbol periods; f in cycles/symbol. Hold Fs is up/den, not up.
    f = np.linspace(0, (1+alpha)/2, 16385)
    t = (np.arange(span*up) - (span*up-1)/2)/up
    a = s.rrc_response(f, alpha)/np.sinc(f/(up/den))
    g = 2*np.trapezoid(a*np.cos(2*np.pi*np.outer(t,f)), f, axis=1)
    g *= np.kaiser(len(g), 1)
    amax = 1 if bits == 3 else np.sqrt(.5)
    worst = np.abs(g.reshape(span,up)).sum(0).max()*amax
    return np.round(g*508/worst*256).astype(np.int64)


def taps(name, peak=128):
    # Each separately rounded part adds at most 0.5 LSB/axis.
    reserve = (len(MODES[name][-1])+1)//2
    return np.trunc(prototype(name)*(peak-reserve)/508).astype(np.int64)


def header_text():
    lines = ['// Generated by host/moon_fill.py --header. Experimental inverse-hold RRC.',
             '#pragma once', '#include <stdint.h>']
    for name in MODES:
        g = prototype(name)
        lines += [f'static const int32_t moon_{name}[{len(g)}] = {{',
                  '    '+', '.join(map(str,g)), '};']
    return '\n'.join(lines)+'\n'


def round_odd(x):
    return np.sign(x)*((np.abs(x)+(1 << 37)) >> 38)


@lru_cache(None)
def parts(name, peak=128, rounded=True):
    up, den, _, _, bits, groups = MODES[name]
    g, result = taps(name,peak), []
    for group in groups:
        w = np.arange(1 << (bits*len(group)))
        code = (w[None,:] >> (bits*np.arange(len(group)-1,-1,-1)[:,None])) & ((1 << bits)-1)
        phase = code if bits == 3 else 2*code+1
        h = den*np.arange(12)[None,:] - up*np.array(group)[:,None]
        coeff = np.where((h >= 0)&(h < len(g)), g[np.clip(h,0,len(g)-1)], 0)
        raw = np.stack([np.einsum('jw,jp->wp', level[phase],coeff)
                        for level in (s.LEVEL_I,s.LEVEL_Q)])
        result.append(round_odd(raw) if rounded else raw/2**38)
    return result


@lru_cache(None)
def table(name, peak=128):
    r = parts(name,peak)
    bias = np.stack([-x.min(1) for x in r])
    bias[0] += 512-bias.sum(0)
    fields = [x+b[:,None,:] for x,b in zip(r,bias)]
    assert all(x.min() >= 0 for x in fields)
    assert (sum(x.max(1) for x in fields) < 1024).all()
    return [(x[0] | x[1] << 10).astype(np.uint32) for x in fields]


def pack(name, phase):
    up, den, _, _, bits, _ = MODES[name]
    block = 12*den//up
    k = np.asarray(phase, np.uint16)
    assert len(k)%block == 0
    if bits == 2:
        assert np.isin(k,[1,3,5,7]).all()
        k = k >> 1
    return np.bitwise_or.reduce(k.reshape(-1,block) << (bits*np.arange(block-1,-1,-1)),axis=1).astype(np.uint16)


def shape(name, phase, peak=128):
    """phase has two whole input blocks of history; same block timeline as firmware."""
    up, den, _, _, bits, groups = MODES[name]
    block = 12*den//up
    k = np.asarray(phase,np.int64)
    code = k if bits == 3 else k >> 1
    start = np.arange(2*block,len(k),block)
    out = np.zeros((len(start),12),np.uint32)
    for group,t in zip(groups,table(name,peak)):
        index = np.zeros(len(start),np.int64)
        for at in group: index = (index << bits) | code[start+at]
        out += t[index]
    return (out ^ s.XOR).ravel()


def linear(name, phase, peak=128):
    """Independent upsample/convolve/downsample oracle, retaining the rational phase."""
    from scipy.signal import upfirdn
    up, den, _, _, _, _ = MODES[name]
    block = 12*den//up
    x = (s.LEVEL_I[phase]+1j*s.LEVEL_Q[phase])/2**30
    y = upfirdn(taps(name,peak)/256, x, up=up, down=den)
    return y[24:len(phase)*up//den]


def sampled_power(name, fn, peak=128):
    up, den = MODES[name][:2]
    g, n = taps(name,peak),up/den
    return sum(10**(s.response_db(g,up,fn+2*j*n,False)/10)
               for j in range(-(den//2),den-den//2))


@lru_cache(None)
def covariance(name, peak=128, rounded=True):
    """Exact time-averaged autocorrelation of the quantized waveform for iid PSK.

    A part is a function of <=4 independent symbol codes. Two parts correlate
    only through their shared symbols. Average each table over the other axes,
    then take the inner product over the shared axes. C[b,p,q] is the covariance
    of output phase p in block 0 with phase q in block b. Average over p to get
    R[lag]. No FFT periodogram or random-noise estimate is used here.
    """
    up,den,_,_,bits,groups = MODES[name]
    block, alphabet = 12*den//up,1 << bits
    values = [(r[0]+1j*r[1]).reshape((alphabet,)*len(group)+(12,))
              for r,group in zip(parts(name,peak,rounded),groups)]
    def marginal(value, keep):
        axes = tuple(j for j in range(value.ndim-1) if j not in keep)
        return value.mean(axis=axes).reshape(-1,12)
    cov = []
    distance = max(max(g) for g in groups)-min(min(g) for g in groups)
    for b in range(distance//block+1):
        c = np.zeros((12,12),complex)
        for group,f in zip(groups,values):
            for other,v in zip(groups,values):
                shifted = tuple(p+b*block for p in other)
                shared = set(group)&set(shifted)
                if not shared: continue  # all part means are exactly zero by odd rounding
                x = marginal(f,[j for j,p in enumerate(group) if p in shared])
                y = marginal(v,[j for j,p in enumerate(shifted) if p in shared])
                c += x.T@y.conj()/len(x)
        cov.append(c)
    return np.array([sum(cov[(p+lag)//12][p,(p+lag)%12]
                        for p in range(12) if (p+lag)//12 < len(cov))/12
                     for lag in range(12*len(cov))])


def table_power(name, fn, peak=128, rounded=True):
    """PSD = R[0] + 2 Re sum(lag>0, R[lag] exp(j*2*pi*f*lag/Fs))."""
    r = covariance(name,peak,rounded)
    n = MODES[name][0]/MODES[name][1]
    return r[0].real+2*np.real(np.exp(1j*np.pi*np.outer(fn,np.arange(1,len(r)))/n)@r[1:])


def mask(name, peak=128, step=1e-4, quantized=False):
    """Time-averaged pulse PSD after rational sampling and the ideal DAC hold.

    Downsampling by den aliases den copies of the high-rate FIR power response.
    The DAC hold multiplies the sum at the output frequency, not each aliased frequency.
    quantized=True includes every table rounding via its exact autocorrelation.
    Both models exclude the analog radio response.
    """
    up, den, _, alpha, _, _ = MODES[name]
    n = up/den
    upper, lower = (np.array(s.MASK[alpha][k]) for k in ('upper','lower'))
    fn = np.unique(np.r_[np.arange(0,n+step/2,step),upper[:,0],lower[:,0]])
    power = (lambda f: table_power(name,f,peak)) if quantized else (lambda f: sampled_power(name,f,peak))
    db = 10*np.log10(power(fn)/power(np.array([0])))+20*np.log10(np.sinc(fn/(2*n)))
    hi = np.interp(fn,upper[:,0],upper[:,1])-db
    near = fn <= lower[-1,0]
    lo = db[near]-np.interp(fn[near],lower[:,0],lower[:,1])
    far = fn > upper[-1,0]
    return dict(upper_db=float(hi.min()),upper_at_fn=float(fn[hi.argmin()]),
                lower_db=float(lo.min()),lower_at_fn=float(fn[near][lo.argmin()]),
                far_db=float((-40-db[far]).min()))


def symmetry(name, peak=128):
    """Exhaustive C4 identity, signed values only. Does not predict restoration cost."""
    bits = MODES[name][4]
    total = 0
    for group,r in zip(MODES[name][-1],parts(name,peak)):
        w = np.arange(r.shape[1])
        code = np.stack([(w >> (bits*j)) & ((1 << bits)-1) for j in range(len(group)-1,-1,-1)])
        phase = code if bits == 3 else 2*code+1
        rotation = phase[0]//2
        normalized = (phase-2*rotation)&7
        idx = normalized if bits == 3 else normalized >> 1
        index = np.zeros(len(w),np.int64)
        for c in idx: index = (index << bits)|c
        a,b = r[:,index]
        restored = np.stack((np.choose(rotation[:,None],(a,-b,-a,b)),
                             np.choose(rotation[:,None],(b,a,-b,-a))))
        assert np.array_equal(restored,r)
        total += r[:,np.unique(index)].size*2  # I16/Q16, same 4 B/sample as DAC words
    return total


def half_symmetry(name, peak=128):
    """Exact 180-degree XOR format at peak 128, including the +1 correction.

    Each contribution is (I+128) | (Q+128)<<10, with 8-bit fields. Negating
    needs XOR 0x3fcff AND +0x401. The +1 per axis can be accumulated per block.
    XOR alone is one's complement and is wrong even at zero. After summing m
    parts, add (512-128*m + number_negated)*0x401 before the final DAC XOR.
    This proves storage/correctness only; no restoration kernel is claimed.
    """
    bits, total = MODES[name][4],0
    for group,r in zip(MODES[name][-1],parts(name,peak)):
        w = np.arange(r.shape[1])
        code = np.stack([(w >> (bits*j)) & ((1 << bits)-1) for j in range(len(group)-1,-1,-1)])
        phase = code if bits == 3 else 2*code+1
        negative = phase[0] >> 2
        normalized = (phase-4*negative)&7
        idx = normalized if bits == 3 else normalized >> 1
        index = np.zeros(len(w),np.int64)
        for c in idx: index = (index << bits)|c
        fields = r+128
        assert fields.min() >= 0 and fields.max() <= 255
        full = fields[0] | fields[1] << 10
        restored = (full[index] ^ (negative[:,None]*0x3fcff)) + negative[:,None]*0x401
        assert np.array_equal(restored,full)
        total += len(np.unique(index))*12*4
    return total


def report():
    for name, (up,den,span,alpha,bits,_) in MODES.items():
        yield dict(mode=name,evidence='host model, not silicon',sps=up/den,rolloff=alpha,
                   span_symbols=span,taps=len(prototype(name)),table_bytes=sum(x.nbytes for x in table(name)),
                   half_table_bytes=half_symmetry(name),
                   quarter_table_bytes=symmetry(name),mask=mask(name),mask_quantized=mask(name,quantized=True),
                   table_check=s.checksum(np.concatenate(table(name)).ravel()))


def cycle_report(disassembly):
    import math
    import shaper_cycles as c
    code = c.functions(disassembly)
    for name, func in zip(MODES,('shaper_moon3_pie','shaper_moon24q_pie','shaper_moon24p_pie')):
        f = code[func]
        first = c.replay(c.loop_stream(f,1))['cycles']
        step = c.replay(c.loop_stream(f,2))['cycles']-first
        base = first-step
        yield dict(kind='kernel',mode=name,evidence='assembled issue model, not silicon',
                   cycles_per_block=step,cycles_per_sample=step/12,
                   **c.replay(c.loop_stream(f,1365)))
        def bank(k):
            first = k*15740-128 if k else 0
            previous = (k-1)*15740-128+16380 if k > 1 else 16380 if k else 0
            offset = first%16380
            pieces = [(first,16380-offset)]+([(first+16380-offset,offset)] if offset else [])
            kernel = fresh = saved = partial = inputs = 0
            for at,count in pieces:
                off = at%16380
                keep = max(0,768-off) if off and count == 16380-off else 768
                start = max(at,previous)
                count = max(0,at+count-start)
                if not count: continue
                fresh += count
                saved += min(count,keep)
                skip = start%12
                head = min(count,12-skip) if skip else 0
                groups,tail = divmod(count-head,12)
                calls = bool(head)+bool(groups)+bool(tail)
                kernel += calls*base+(bool(head)+groups+bool(tail))*step
                partial += head+tail
                inputs += 2*(2+math.ceil((skip+count)/12))
            copy = .5*(16380-fresh+saved)
            # Planning assumptions, never a calibrated silicon bound. Staging
            # into uint16_t input blocks is not integrated with the live ring.
            notification, tick, control = 2396 if k else 0,1068,1000
            total = kernel+6*partial+inputs+copy+notification+tick+control
            return dict(bank=k,kernel_cycles=kernel,partial_copy_cycles=6*partial,
                        assumed_input_cycles=inputs,sample_copy_cycles=copy,
                        notification_allowance_cycles=notification,tick_allowance_cycles=tick,
                        assumed_control_cycles=control,modelled_fill_cycles=total,
                        deadline_cycles=47220,target_cycles=40137)
        yield dict(kind='startup_fill',mode=name,evidence='uncalibrated model',**bank(0))
        worst = max((bank(k) for k in range(1,820)),key=lambda r:r['modelled_fill_cycles'])
        yield dict(kind='steady_fill',mode=name,evidence='uncalibrated model',**worst)


def check_membench(path):
    rows = [json.loads(line.lstrip('@')) for line in pathlib.Path(path).read_text().splitlines()
            if line.lstrip('@').startswith('{')]
    for mode,name in enumerate(tuple(MODES)[:3]):
        meta = [r for r in rows if r.get('cmd') == 'membench moon' and r.get('mode') == mode]
        timed = [r for r in rows if r.get('test') == f'moon{mode}_pie']
        assert len(meta) == len(timed) == 1,(meta,timed)
        meta,r = meta[0],timed[0]
        assert 'error' not in meta,meta
        assert meta['table_bytes'] == sum(t.nbytes for t in table(name)),meta
        assert meta['internal_heap_bytes'] == (24576,0,49152)[mode],meta
        assert meta['table_check'] == s.checksum(np.concatenate(table(name)).ravel()),meta
        up,den,_,_,bits,_ = MODES[name]
        block = 12*den//up
        x,src = 2026,[]
        for _ in range(1367):
            x ^= x << 13 & 0xffffffff
            x ^= x >> 17
            x ^= x << 5 & 0xffffffff
            src.append(x & ((1 << (bits*block))-1))
        phase = (np.array(src)[:,None] >> (bits*np.arange(block-1,-1,-1))) & ((1 << bits)-1)
        phase = phase.ravel() if bits == 3 else 2*phase.ravel()+1
        assert r['words'] == 16380 and r['check'] == meta['expected'] == s.checksum(shape(name,phase)),r
        print(json.dumps(dict(mode=name,correct=True,kernel_cycles=r['cycles_median'],
                              probe_target_cycles=34137,
                              probe_target_met=r['cycles_median'] <= 34137,
                              admission='requires complete stream and Wi-Fi checks')))


def loopback(name, modcod, output, receiver, native):
    import decode
    import dvbs2
    import onair
    up, den, _, alpha, bits, _ = MODES[name]
    assert (modcod < 12) == (bits == 2)
    block = 12*den//up
    frames = 16
    data = np.frombuffer(onair.payload(modcod,frames,'N0CALL'),np.uint8).reshape(frames,-1)
    phase = []
    rate,modulation = onair.mode(modcod)
    for payload in data:
        bb = dvbs2.bbframe(np.unpackbits(payload),rate,ro=alpha)
        fec = dvbs2.fecframe(bb,rate)
        phase.append(dvbs2.plframe_phases(fec,rate,modulation=modulation))
    phase = np.concatenate(phase)
    pad = (-len(phase))%block
    phase = np.r_[np.full(2*block,1 if bits == 2 else 0),phase,np.full(pad,1 if bits == 2 else 0)].astype(np.uint8)
    words = shape(name,phase)
    output.mkdir(parents=True,exist_ok=True)
    packed = output/f'{name}-{modcod}.u16'
    native_words = output/f'{name}-{modcod}.words'
    pack(name,phase).astype('<u2').tofile(packed)
    subprocess.run([str(native),str(tuple(MODES).index(name)),str(packed),str(native_words)],check=True)
    actual = np.fromfile(native_words,dtype='<u4')
    assert np.array_equal(actual,words),name
    words = actual
    z = s.iq(words)
    iq = np.column_stack((z.real,z.imag)).astype('<i2')
    crc = zlib.crc32(iq.tobytes())
    golden = json.loads((ROOT/'tests/data/moon_waveform_crcs.json').read_text())
    assert crc == golden[f'{name}/{modcod}'],(name,modcod,crc)
    path = output/f'{name}-{modcod}.iq'
    iq.tofile(path)
    cf = output/f'{name}-{modcod}.cfile'
    (z/512).astype('<c8').tofile(cf)
    record, got = decode.decode(cf,sample_rate=80e6,symbol_rate=80e6*den/up,alpha=alpha,
                                 receiver=receiver,log=output/f'{name}-{modcod}.log')
    per = data.shape[1]
    at = onair.stream_match(data.tobytes(),got,per)
    assert at is not None and len(got)//per >= (14 if bits == 2 else 12),record
    assert record['bch_failed_frames'] == 0 and record['ldpc_bit_flips'] == 0,record
    assert record['ldpc_checks_before'] == record['ldpc_checks_after'] == 0,record
    assert record['bch_corrected_bits'] == 0 and record['bbheader_rejected_frames'] == 0,record
    record.update(mode=name,modcod=modcod,source='native C shaper, Python encoder',input_frames=frames,
                  contiguous_frames=len(got)//per,payload_bit_errors=0,first_frame=at//per,
                  iq_crc32=crc)
    (output/f'{name}-{modcod}.json').write_text(json.dumps(record,sort_keys=True)+'\n')
    return record


def build_native(folder):
    (folder/'esp_attr.h').write_text('#define IRAM_ATTR\n')
    exe = folder/'moon'
    subprocess.run(['cc','-O2','-Wall','-Wextra','-Werror','-DMOON_HOST',f'-I{folder}',
                    f'-I{ROOT}/firmware/main',str(ROOT/'tests/moon_fill.c'),
                    str(ROOT/'firmware/main/shaper_moon.c'),'-o',str(exe)],check=True)
    return exe


