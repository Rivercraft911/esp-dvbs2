"""Generate the portable encoder's constant tables from the standard's code tables.

EN 302 307-1 V1.4.1: Tables 5a, 6a and 7a, Annex B, clauses 5.2.2 and 5.5.4.
No encoder implementation or prior-art code is used. Run with --check in host tests.
"""
import argparse
import pathlib

from dvbs2_tables import BCH_PARAMS, BCH_POLYS, LDPC, Q

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "firmware/components/dvbs2/tables.h"
RATES = ("1/2", "3/5", "2/3", "3/4", "4/5", "5/6", "8/9", "9/10")


def multiply(a, b):
    product = 0
    while b:
        if b & 1:
            product ^= a
        a, b = a << 1, b >> 1
    return product


def array(name, ctype, values, columns=12):
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for k in range(0, len(values), columns):
        out.append("    " + ", ".join(str(v) for v in values[k:k + columns]) + ",")
    return "\n".join(out + ["};\n"])


def generate():
    out = ["/* Generated by host/gen_dvbs2_c.py; do not edit. */\n"]
    reverse = [int(f"{b:08b}"[::-1], 2) for b in range(256)]
    out.append(array("reverse_byte", "uint8_t", reverse, 16))
    for t in (8, 10, 12):
        g = 1
        for powers in BCH_POLYS["normal"][:t]:
            g = multiply(g, sum(1 << k for k in powers))
        r = g.bit_length() - 1
        words = r // 32
        out.append(f"static const uint32_t bch_{t}[256][6] = {{")
        for b in range(256):
            reg = b << (r - 8)
            for _ in range(8):
                reg = (reg << 1) ^ (g if (reg >> (r - 1)) & 1 else 0)
            vals = [(reg >> (32 * (words - 1 - k))) & 0xffffffff for k in range(words)]
            vals += [0] * (6 - words)
            out.append("    {" + ", ".join(f"0x{v:08x}u" for v in vals) + "},")
        out.append("};\n")
    for k, rate in enumerate(RATES):
        q = Q["normal"][rate]
        rows = LDPC[("normal", rate)]
        assert len(rows) * 360 == BCH_PARAMS["normal"][rate][1]
        entries = []
        for row in rows:
            entries.append(len(row))
            # x = r + q*c. Encode r,c once rather than dividing on the CPU.
            entries.extend(((x % q) << 9) | (x // q) for x in row)
        out.append(array(f"ldpc_{k}", "uint16_t", entries))
    state = 0b000000010101001
    prbs = []
    for _ in range(max(BCH_PARAMS["normal"][rate][0] for rate in RATES) // 8):
        byte = 0
        for _ in range(8):
            bit = ((state >> 13) ^ (state >> 14)) & 1
            state = ((state << 1) | bit) & 0x7fff
            byte = (byte << 1) | bit
        prbs.append(byte)
    out.append(array("bb_prbs", "uint8_t", prbs, 16))
    # The Gold generators are periodic at 2**18-1. Pack four pi/2
    # rotations per byte, earliest symbol in bits 1:0.
    period = (1 << 18) - 1
    x, y = bytearray(period), bytearray([1]) * period
    x[0] = 1
    for k in range(period - 18):
        x[k + 18] = x[k + 7] ^ x[k]
        y[k + 18] = y[k + 10] ^ y[k + 7] ^ y[k + 5] ^ y[k]
    rotations = []
    for k in range(0, 33192, 4):
        byte = 0
        for j in range(4):
            i = k + j
            z0 = x[i] ^ y[i]
            zi = (i + 131072) % period
            z1 = x[zi] ^ y[zi]
            byte |= (2 * z1 + z0) << (2 * j)
        rotations.append(byte)
    out.append(array("pl_rotations", "uint8_t", rotations, 16))
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit(f"stale generated file: {OUTPUT}; run python3 host/gen_dvbs2_c.py")
        print("C tables match the standard-derived generator")
    else:
        OUTPUT.write_text(text)
        print(OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
