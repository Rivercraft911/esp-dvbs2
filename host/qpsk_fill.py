#!/usr/bin/env python3
"""Four-symbol QPSK tables, independent sample oracle and assembled issue model. No devices."""
import argparse
import json
import pathlib
import numpy as np
import shaper as s

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADER = ROOT / 'firmware/main/shaper_qpsk_taps.h'


def pulse(n, level=128):
    p = s.Profile(f'qpsk-n{n}', .35, n, 'qpsk')
    return np.trunc(p.taps * ((level - 2) / 508)).astype(np.int64)


def parts(n, level=128):
    """Independent convolution of each four-symbol group's contribution, rounded once."""
    taps = pulse(n, level)
    result = np.zeros((2, 3, 256, 4*n), np.int64)
    for axis, levels in enumerate((s.LEVEL_I, s.LEVEL_Q)):
        for part in range(3):
            for j in range(4):
                position = 3 - j - 4*part
                phase = 2*((np.arange(256) >> (2*j)) & 3) + 1
                for p in range(4*n):
                    age = p//n - position
                    if 0 <= age < 9:
                        result[axis,part,:,p] += levels[phase] * taps[age*n+p%n]
    return (result + (1 << (s.SHIFT-1))) >> s.SHIFT


def table(n, level=128):
    r = parts(n, level)
    bias = -r.min(axis=2)
    # Middle group is present in every sample, and takes the remaining offset.
    bias[:,1] = 512 - bias[:,0] - bias[:,2]
    fields = r + bias[:,:,None,:]
    assert fields.min() >= 0
    assert (fields.max(axis=2).sum(axis=1) <= 1023).all()
    return (fields[0] | fields[1] << 10).astype(np.uint32)


def pack(phases):
    k = np.asarray(phases, np.uint8)
    assert len(k) % 4 == 0 and np.isin(k, [1,3,5,7]).all()
    q = (k >> 1).reshape(-1,4).astype(np.uint16)
    return (q[:,0]<<6 | q[:,1]<<4 | q[:,2]<<2 | q[:,3]).astype(np.uint8)


def shape(src, n, level=128):
    """src includes two history bytes. Vectorized table model, block order fixed globally."""
    t = table(n, level)
    return ((t[0,src[2:]] + t[1,src[1:-1]] + t[2,src[:-2]]) ^ s.XOR).ravel()


def header_text():
    lines = ['// Generated by host/qpsk_fill.py --header. Nine-symbol inverse-hold RRC, alpha .35.',
             '#pragma once', '#include <stdint.h>']
    for n in (3,4):
        taps = s.Profile(f'qpsk-n{n}', .35, n, 'qpsk').taps
        lines.append(f'static const int32_t qpsk_taps{n}[{9*n}] = {{')
        lines.append('    ' + ', '.join(map(str,taps)) + '\n};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--header', action='store_true')
    args = ap.parse_args()
    if args.header:
        HEADER.write_text(header_text())
    else:
        for n in (3,4):
            print(json.dumps(dict(sps=n, table_bytes=table(n).nbytes,
                                  table_check=s.checksum(table(n).ravel()),
                                  mask=s.mask_margins(pulse(n),n,.35))))
