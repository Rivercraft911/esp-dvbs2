"""Correctness pulse for 80/3 and 100/3 Msym/s; no timing prediction.

Time is in symbols. At 100/3 Msym/s sample n is at 5*n/12; all twelve
fractional phases share one inverse-hold-corrected RRC pulse. EN 302 307-1
5.6 and Annex A define the ideal response and mask, not this finite FIR.
"""
import argparse
import pathlib
import numpy as np
import shaper

ROOT = pathlib.Path(__file__).resolve().parents[1]


def taps(num=12, den=5, span=12, alpha=.2):
    f = np.linspace(0, (1 + alpha)/2, 16385)  # cycles/symbol
    t = (np.arange(span*num) - (span*num-1)/2)/num
    amplitude = shaper.rrc_response(f, alpha)/np.sinc(f*den/num)
    pulse = np.concatenate([2*np.trapezoid(amplitude*np.cos(2*np.pi*np.outer(ti, f)), f, axis=1)
                            for ti in np.array_split(t, 1+len(t)//64)])
    pulse *= np.kaiser(span*num, 1)
    bound = np.abs(pulse.reshape(span, num)).sum(axis=0).max()
    # Q15 taps in DAC LSB, peak 128. Coordinate quantization is bounded separately.
    return np.rint(pulse * 126/bound * 32768).astype(np.int32)


def shape(phases, first, count, coeff, num, den):
    """Integer oracle, zero phase before symbol zero, output int16 I/Q."""
    phases = np.asarray(phases, dtype=np.uint8)
    level = np.rint(32768*np.exp(1j*np.arange(8)*np.pi/4))
    coords = np.column_stack((level.real, level.imag)).astype(np.int64)
    out = np.zeros((count, 2), dtype=np.int64)
    at = (first + np.arange(count, dtype=np.int64))*den
    symbol, phase = at//num, at%num
    for age in range(len(coeff)//num):
        k = symbol-age
        code = np.where(k >= 0, phases[np.maximum(k, 0)], 0)
        out += coords[code] * coeff[age*num+phase, None]
    return ((out + (1 << 29)) >> 30).astype('<i2')


def mask(coeff, num, den, alpha):
    # Sum power of every aliased pulse replica after downsampling, then DAC hold.
    up, lo = (np.array(shaper.MASK[alpha][k], float) for k in ('upper','lower'))
    fn = np.unique(np.r_[np.arange(0, num/den, .0002), up[:,0], lo[:,0]])
    f = fn/2
    k = np.arange(len(coeff))-(len(coeff)-1)/2
    power = np.zeros_like(f)
    for alias in range(-den//2-1, den//2+2):
        freq = f + alias*num/den
        valid = abs(freq) <= num/2
        response = np.zeros_like(f)
        response[valid] = np.cos(2*np.pi*np.outer(freq[valid], k)/num) @ coeff
        power += response**2
    db = 10*np.log10(np.maximum(power, 1e-30)/power[0])+20*np.log10(abs(np.sinc(f*den/num)))
    near, lower = fn <= up[-1,0], fn <= lo[-1,0]
    return dict(upper=float(min(np.interp(fn[near],up[:,0],up[:,1])-db[near])),
                lower=float(min(db[lower]-np.interp(fn[lower],lo[:,0],lo[:,1]))),
                far=float(min(-40-db[~near])))


def header():
    out = ['// Generated by host/rational.py; Q15 DAC LSB taps at peak 128.', '#pragma once', '#include <stdint.h>']
    for name,args in (('a20',(12,5,12,.2)),('a35',(3,1,9,.35))):
        v = taps(*args)
        out.append(f'static const int32_t rational_{name}[{len(v)}] = {{')
        out += ['    '+', '.join(map(str,v[i:i+12]))+',' for i in range(0,len(v),12)]
        out.append('};')
    return '\n'.join(out)+'\n'


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header', action='store_true')
    a = p.parse_args()
    if a.header:
        (ROOT/'firmware/main/shaper_rational_taps.h').write_text(header())
    else:
        for args in ((12,5,12,.2),(3,1,9,.35)):
            print(args, mask(taps(*args),args[0],args[1],args[3]))
