"""Generate the QPSK axis renderer's fixed 80-symbol window schedule.

Each I/Q stream contains the preceding/current sixteen sign bits. The three
four-sample vectors use windows offset by 3, 2 and 0 from the group's newest
sign. Twelve-bit extraction leaves four disposable address bits for VLD.
"""
import argparse
import pathlib

OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "firmware/components/shaper/machine_axis_pie.S"


def generate():
    source = '''/* Generated by tests/reference/gen_machine_axis.py.
 * Direct compact-axis rendering. Eighty symbols / 192 samples per run.
 * Disjoint I/Q fields sum to less than 2^20: OR equals signed saturated ADD.
 * ADDS.ST stores the previous sum while computing the next vector's sum.
 * src is five words per run, no guard load; history holds the preceding
 * sixteen I/Q signs, oldest in bits 15/31. dst is 16-byte aligned. */
    .section .iram1.machine_axis,"ax"
    .balign 32 // measured fetch position (stream_assert.ld)
    .global machine_axis_render_pie
    .type machine_axis_render_pie,@function
machine_axis_render_pie:
    entry a1,32
    beqz a4,.Laxis_done
    extui a12,a5,0,16
    srli a13,a5,16
    movi a7,4096
    add a7,a7,a6
    movi a8,8192
    add a8,a8,a6
    movi a9,12288
    add a9,a9,a6
    movi a10,16384
    add a10,a10,a6
    movi a11,20480
    add a11,a11,a6
    loopnez a4,.Laxis_end
'''
    addresses = []
    for word in range(5):
        setup = f"    l32i a15,a3,{4*word}\n"
        if word == 0:
            setup += "    ssai 16\n"
        setup += "    src a5,a15,a15\n    src a12,a12,a5\n    src a13,a13,a15\n"
        for end in range(5, 81, 5):
            if (end-1)//16 != word:
                continue
            remaining = 16-(end-16*word)
            for vector, window in enumerate((3, 2, 0)):
                scalar, setup = setup, ""
                shift = remaining+window-4
                for dst, src in (("a5", "a12"), ("a14", "a13")):
                    if shift >= 0:
                        scalar += f"    extui {dst},{src},{shift},12\n"
                    else:
                        scalar += f"    extui {dst},{src},{remaining+window},8\n"
                        scalar += f"    slli {dst},{dst},4\n"
                scalar += f"    add a5,a5,a{6+vector}\n    add a14,a14,a{9+vector}\n"
                addresses.append(scalar)
    assert len(addresses) == 48
    source += addresses[0]
    for vector in range(48):
        qi = 0 if vector % 2 == 0 else 2
        next_addresses = addresses[vector+1] if vector < 47 else "    addi a3,a3,20\n"
        preload = ""
        if next_addresses.startswith("    l32i a15,"):
            preload, next_addresses = next_addresses.split("\n", 1)
            preload += "\n"
        source += f"    ee.vld.128.ip q{qi},a5,0\n"
        source += preload
        source += f"    ee.vld.128.ip q{qi+1},a14,0\n"
        # Next addresses hide vector load latency; the next plane-word load is
        # issued before the independent Q load to avoid a scalar load interlock.
        source += next_addresses
        if vector == 0:
            source += "    ee.orq q0,q0,q1\n"
        else:
            previous = 2 if qi == 0 else 0
            source += f"    ee.vadds.s32.st.incp q{previous},a2,q{qi},q{qi},q{qi+1}\n"
    source += '''    ee.vst.128.ip q2,a2,16
.Laxis_end:
.Laxis_done:
    retw
    .size machine_axis_render_pie,.-machine_axis_render_pie
'''
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert OUTPUT.read_text() == source, "stale axis renderer: regenerate it"
    else:
        OUTPUT.write_text(source)


if __name__ == "__main__":
    main()
