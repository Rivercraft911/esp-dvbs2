"""Receiver LDPC edges for short QPSK FECFRAMEs (MODCOD 4..10), in quasi-cyclic form.

EN 302 307-1 V1.4.1: Tables 5b and 7b, Annex C, clause 5.3.2. Check c = r + q t
(r = c mod q) is row group r, position t. An Annex C address x = r + q s in the row of
information group g connects check (r, t) to bit (t - s) mod 360 of group g. Parity
bit p_(r + q t) is bit t of parity group r; check (r, t) also reads parity groups r and
r - 1 at shift 0, or group q - 1 at shift 1 for r = 0 (check 0 has no p_(-1)).
Run with --check in host tests.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "host"))

from dvbs2_tables import BCH_PARAMS, LDPC, Q  # noqa: E402

OUTPUT = ROOT / "firmware/components/dvbs2rx/rx_fec_tables.h"
RATES = ("1/2", "3/5", "2/3", "3/4", "4/5", "5/6", "8/9")   # MODCOD 4..10


def edges(rate):
    """Row groups as lists of (group, shift): information edges in Annex C order, then
    parity group r and the previous parity group."""
    q, groups = Q["short"][rate], BCH_PARAMS["short"][rate][1] // 360
    rows = [[] for _ in range(q)]
    for g, xs in enumerate(LDPC[("short", rate)]):
        for x in xs:
            rows[x % q].append((g, x // q))
    for r in range(q):
        rows[r] += [(groups + r, 0), (groups + q - 1, 1) if r == 0 else (groups + r - 1, 0)]
    return rows


def array(name, ctype, values, columns=12):
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for k in range(0, len(values), columns):
        out.append("    " + ", ".join(str(v) for v in values[k:k + columns]) + ",")
    return "\n".join(out + ["};\n"])


def generate():
    out = ["/* Generated by tests/reference/gen_rx_fec.py; do not edit. */\n"]
    out.append("/* Per MODCOD 4..10, each row group's edge count followed by its edges as\n"
               " * group * 512 + shift. */")
    for k, rate in enumerate(RATES):
        values = []
        for row in edges(rate):
            values.append(len(row))
            values += [512 * g + s for g, s in row]
        out.append(array(f"rx_edges_{k}", "uint16_t", values))
    out.append("static const uint16_t *const rx_edges[] = {" +
               ", ".join(f"rx_edges_{k}" for k in range(len(RATES))) + "};\n")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("stale receiver FEC tables: run python3 tests/reference/gen_rx_fec.py")
        print("receiver FEC tables match the standard-derived generator")
    else:
        OUTPUT.write_text(text)
        print(OUTPUT.name)


if __name__ == "__main__":
    main()
