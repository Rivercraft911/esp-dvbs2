"""Immutable fast-encoder tables, shared across modes in flash.

Derived from dvbs2_tables.py, EN 302 307-1 V1.4.1 clauses 5.2.2,
5.3.1, 5.3.2, 5.3.3 and 5.5.4. No encoder implementation is imported.
"""
import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "host"))

from gen_dvbs2_c import RATES, multiply
from dvbs2_tables import BCH_PARAMS, BCH_POLYS, LDPC, Q

OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "firmware/components/dvbs2/fast_tables.h"


def array(name, ctype, values, columns=16):
    width = {"uint8_t": 2, "uint16_t": 4, "uint32_t": 8}[ctype]
    out = [f"static const {ctype} {name}[{len(values)}] __attribute__((aligned(16))) = {{"]
    for k in range(0, len(values), columns):
        out.append("    " + ", ".join(f"0x{v:0{width}x}" for v in values[k:k + columns]) + ",")
    return "\n".join(out + ["};\n"])


def bch(t):
    g = 1
    for powers in BCH_POLYS["normal"][:t]:
        g = multiply(g, sum(1 << k for k in powers))
    r = g.bit_length() - 1
    table = bytearray(4096)
    for k in range(8):
        for v in range(16):
            rem = v << (r + 4 * (7 - k))
            while rem.bit_length() > r:
                rem ^= g << (rem.bit_length() - r - 1)
            row = rem.to_bytes(r // 8, "big")
            at = 512 * k + 16 * v
            table[at:at + 16] = row[:16]
            table[at + 256:at + 256 + len(row) - 16] = row[16:]
    return table


def bch_byte(t):
    g = 1
    for powers in BCH_POLYS["normal"][:t]:
        g = multiply(g, sum(1 << k for k in powers))
    r = g.bit_length() - 1
    table = bytearray(8192)
    for v in range(256):
        rem = v << r
        while rem.bit_length() > r:
            rem ^= g << (rem.bit_length() - r - 1)
        row = rem.to_bytes(r // 8, "big")
        table[16*v:16*v+16] = row[:16]
        table[4096+16*v:4096+16*v+len(row)-16] = row[16:]
    return table


def bch_pair():
    # t=8 has a 128-bit remainder. Two byte tables advance it by 16 bits:
    # R' = (R << 16) XOR T0[head0 ^ b0] XOR T1[head1 ^ b1].
    g = 1
    for powers in BCH_POLYS["normal"][:8]:
        g = multiply(g, sum(1 << k for k in powers))
    table = bytearray()
    for shift in (136, 128):
        for v in range(256):
            rem = v << shift
            while rem.bit_length() > 128:
                rem ^= g << (rem.bit_length() - 129)
            table.extend(rem.to_bytes(16, "big"))
    return table


def program(rate):
    q = Q["normal"][rate]
    rows = [[] for _ in range(q)]
    for group, edges in enumerate(LDPC["normal", rate]):
        for x in edges:
            s = (360 - x // q) % 360
            rows[x % q].append((s % 8, 96 * group + s // 8))
    out = []
    for row in rows:
        top = max((b for b, _ in row), default=0)
        out.append(top + 1)
        for b in range(top, -1, -1):
            offsets = [offset for shift, offset in row if shift == b]
            out.extend([len(offsets), *offsets])
    return out


def rotations():
    period = (1 << 18) - 1
    x, y = bytearray(period), bytearray([1]) * period
    x[0] = 1
    for k in range(period - 18):
        x[k + 18] = x[k + 7] ^ x[k]
        y[k + 18] = y[k + 10] ^ y[k + 7] ^ y[k + 5] ^ y[k]
    return [(x[k] ^ y[k]) + 2 * (x[(k + 131072) % period] ^ y[(k + 131072) % period])
            for k in range(33192)]


def generate():
    out = ["/* Generated by tests/reference/gen_dvbs2_fast.py; do not edit. */\n"]
    for t in (8, 10, 12):
        out.append(array(f"fast_bch_{t}", "uint8_t", bch(t)))
    for t in (10, 12):
        out.append(array(f"fast_bch_byte_{t}", "uint8_t", bch_byte(t)))
    out.append(array("fast_bch_pair_8", "uint8_t", bch_pair()))
    rot = rotations()
    for bps in (2, 3):
        words = []
        for v in range(256 if bps == 2 else 1024):
            word = 0
            for i in range(2 if bps == 3 else 4):
                if bps == 3:
                    phase = (((v >> (1 - i)) & 1) ^ 1) | (((v >> (9 - i)) & 1) << 1) | (((v >> (5 - i)) & 1) << 2)
                else:
                    phase = 1 | (((v >> (6 - 2 * i)) & 1) << 1) | (((v >> (7 - 2 * i)) & 1) << 2)
                word |= phase << (8 * i)
            words.append(word)
        out.append(array(f"fast_map_{bps}", "uint32_t", words, 8))
        if bps == 2:
            packed = [sum(((word >> (8*i)) & 7) << (4*i) for i in range(4))
                      for word in words]
            out.append(array("fast_map_2_packed", "uint32_t", packed, 8))
        for pilots in (0, 1):
            gold = bytearray(8128 if bps == 2 else 5440)
            for k in range(64800 // bps):
                r = rot[k + (36 * (k // 1440) if pilots else 0)]
                if bps == 3:
                    gold[k // 8] |= (r & 1) << (7 - k % 8)
                    gold[2720 + k // 8] |= (r >> 1) << (7 - k % 8)
                else:
                    gold[k // 4] |= ((r >> 1) << (7 - 2 * (k % 4))) | ((r & 1) << (6 - 2 * (k % 4)))
            out.append(array(f"fast_gold_{bps}_{pilots}", "uint8_t", gold))
    # Four symbols straight to two packed bytes. The index is the existing
    # P0'/P2/P1 nibble triple, first symbol in each nibble's high bit.
    packed = []
    # P1's high bit toggles only bit 1 of the result. The runner applies that
    # XOR, halving the table to 8 KiB without another lookup.
    for v in range(2048):
        word = 0
        for i in range(4):
            bit = 3 - i
            phase = (((v >> bit) & 1) ^ 1) | (((v >> (8 + bit)) & 1) << 1) | (((v >> (4 + bit)) & 1) << 2)
            word |= phase << (4 * i)
        packed.append(word)
    out.append(array("fast_map_3_packed", "uint32_t", packed, 8))
    # Header and pilot phases depend only on MODCOD/pilots and code 0.
    generators = (0x55555555, 0x33333333, 0x0f0f0f0f, 0x00ff00ff, 0x0000ffff)
    headers = []
    for modcod in range(4, 18):
        y = 0
        for k, generator in enumerate(generators):
            if (modcod >> (4 - k)) & 1:
                y ^= generator
        for pilots in (0, 1):
            for k in range(90):
                if k < 26:
                    bit = (0x18d2e82 >> (25 - k)) & 1
                else:
                    j = k - 26
                    bit = ((y >> (31 - j // 2)) ^ (0x719d83c953422dfa >> (63 - j)) ^ (pilots & j)) & 1
                headers.append((3 if k % 2 else 1) + 4 * bit)
    out.append(array("fast_headers", "uint8_t", headers))
    out.append(array("fast_pilots", "uint8_t", [(1 + 2 * rot[1440*(b+1) + 36*b + j]) & 7
                                                for b in range(22) for j in range(36)]))
    for i, rate in enumerate(RATES):
        out.append(array(f"fast_prog_{i}", "uint16_t", program(rate), 12))
    out.append("static const uint16_t *const fast_prog[] = {" +
               ", ".join(f"fast_prog_{i}" for i in range(len(RATES))) + "};\n")
    out.append(array("fast_cols", "uint16_t", [48 * (8 * (3 - (t % 32) // 8) + t % 8) + 4 * (t // 32) for t in range(360)], 12))
    crc = []
    for v in range(256):
        for _ in range(8):
            v = ((v << 1) ^ (0xd5 if v & 128 else 0)) & 255
        crc.append(v)
    tables = crc[:]
    for _ in range(3):
        tables.extend(crc[v] for v in tables[-256:])
    out.append(array("fast_crc8", "uint8_t", tables))
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("stale fast tables: run python3 tests/reference/gen_dvbs2_fast.py")
        print("fast tables match the standard-derived generator")
    else:
        OUTPUT.write_text(text)
        print(OUTPUT.name)


if __name__ == "__main__":
    main()
